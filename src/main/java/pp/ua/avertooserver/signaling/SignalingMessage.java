package pp.ua.avertooserver.signaling;

import java.util.UUID;

/**
 * Вхідний WebRTC-сигнал від одного пристрою до іншого.
 *
 * Сервер не обробляє вміст payload і не передає через цей
 * канал повідомлення чату. Він лише пересилає сигналізацію,
 * необхідну для встановлення прямого WebRTC-з'єднання.
 */
public record SignalingMessage(

        /**
         * Публічний числовий ID користувача, якому адресовано сигнал.
         */
        Long targetUserId,

        /**
         * ID приватного чату, у межах якого відбуваються переговори.
         */
        UUID chatId,

        /**
         * Унікальний ID конкретної спроби WebRTC-переговорів.
         *
         * Ініціатор створює його перед початком переговорів.
         * Той самий ID використовують OFFER, ANSWER та ICE
         * у межах цієї спроби.
         */
        UUID negotiationId,

        /**
         * Тип сигналу, наприклад OFFER, ANSWER або ICE.
         */
        String type,

        /**
         * Дані сигналізації у форматі, погодженому клієнтами.
         *
         * Це не текст повідомлення чату.
         */
        String payload

) {
}