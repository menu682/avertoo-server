package pp.ua.avertooserver.common.exception;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;
import pp.ua.avertooserver.common.exception.dto.ErrorResponse;

import java.util.Objects;

/**
 * Centralized exception handler for REST API endpoints.
 *
 * <p>Converts application exceptions into consistent HTTP responses
 * containing an HTTP status code and an error message.</p>
 */
@RestControllerAdvice
public class GlobalExceptionHandler {

    /**
     * Handles requests for users that do not exist.
     *
     * @param exception exception containing the requested user information
     * @return HTTP 404 response with an error description
     */
    @ExceptionHandler(UserNotFoundException.class)
    public ResponseEntity<ErrorResponse> handleUserNotFound(
            UserNotFoundException exception
    ) {

        ErrorResponse response = new ErrorResponse(
                HttpStatus.NOT_FOUND.value(),
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.NOT_FOUND)
                .body(response);
    }

    /**
     * Handles validation errors produced by Jakarta Bean Validation.
     *
     * <p>The first available validation message is returned to the client.
     * This keeps validation responses simple and consistent for mobile
     * and other API clients.</p>
     *
     * @param exception validation exception generated by Spring
     * @return HTTP 400 response with the validation error
     */
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<ErrorResponse> handleValidationException(
            MethodArgumentNotValidException exception
    ) {

        String message = getValidationMessage(exception);

        ErrorResponse response = new ErrorResponse(
                HttpStatus.BAD_REQUEST.value(),
                message
        );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(response);
    }

    /**
     * Handles failed CAPTCHA verification.
     *
     * <p>A failed CAPTCHA means that the client has not passed the
     * anti-abuse verification required for the protected operation.</p>
     *
     * @param exception CAPTCHA verification exception
     * @return HTTP 400 response indicating that CAPTCHA verification failed
     */
    @ExceptionHandler(CaptchaVerificationException.class)
    public ResponseEntity<ErrorResponse> handleCaptchaVerification(
            CaptchaVerificationException exception
    ) {

        ErrorResponse response = new ErrorResponse(
                HttpStatus.BAD_REQUEST.value(),
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.BAD_REQUEST)
                .body(response);
    }

    /**
     * Handles authentication failures such as an unknown user or
     * an incorrect password.
     *
     * @param exception authentication exception
     * @return HTTP 401 response
     */
    @ExceptionHandler(InvalidCredentialsException.class)
    public ResponseEntity<ErrorResponse> handleInvalidCredentials(
            InvalidCredentialsException exception
    ) {

        ErrorResponse response = new ErrorResponse(
                HttpStatus.UNAUTHORIZED.value(),
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.UNAUTHORIZED)
                .body(response);
    }

    /**
     * Handles registration requests that exceed the configured rate limit.
     *
     * @param exception rate-limit exception
     * @return HTTP 429 response
     */
    @ExceptionHandler(RegistrationRateLimitExceededException.class)
    public ResponseEntity<ErrorResponse> handleRegistrationRateLimitExceeded(
            RegistrationRateLimitExceededException exception
    ) {

        ErrorResponse response = new ErrorResponse(
                HttpStatus.TOO_MANY_REQUESTS.value(),
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.TOO_MANY_REQUESTS)
                .body(response);
    }

    /**
     * Handles login requests that exceed the configured rate limit.
     *
     * @param exception rate-limit exception
     * @return HTTP 429 response
     */
    @ExceptionHandler(LoginRateLimitExceededException.class)
    public ResponseEntity<ErrorResponse> handleLoginRateLimitExceeded(
            LoginRateLimitExceededException exception
    ) {

        ErrorResponse response = new ErrorResponse(
                HttpStatus.TOO_MANY_REQUESTS.value(),
                exception.getMessage()
        );

        return ResponseEntity
                .status(HttpStatus.TOO_MANY_REQUESTS)
                .body(response);
    }

    /**
     * Extracts the most useful validation message from Spring's
     * validation errors.
     *
     * <p>NotBlank errors are preferred because they usually provide
     * the clearest message when a required field is missing.</p>
     *
     * @param exception validation exception
     * @return the best available validation message
     */
    private String getValidationMessage(
            MethodArgumentNotValidException exception
    ) {

        return exception.getBindingResult()
                .getFieldErrors()
                .stream()
                .filter(error -> "NotBlank".equals(error.getCode()))
                .map(error -> error.getDefaultMessage())
                .findFirst()
                .orElseGet(() -> exception.getBindingResult()
                        .getFieldErrors()
                        .stream()
                        .map(error -> error.getDefaultMessage())
                        .filter(Objects::nonNull)
                        .findFirst()
                        .orElse("Invalid request"));
    }
}